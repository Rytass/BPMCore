import type { ApprovalInstanceStateEnum } from '../workflow-engine/workflow-engine.enums';

/** Empty payload for event types that carry no type-specific fields. */
export type BPMInstanceEventNoPayload = Readonly<Record<never, never>>;

/**
 * Type-specific fields per event type (ADR 27 §1.3). `formData` is never part
 * of an event: a host that needs it reads the instance by `instanceId`.
 */
export interface BPMInstanceEventTypePayloads {
  readonly INSTANCE_APPROVED: BPMInstanceEventNoPayload;
  readonly INSTANCE_CANCELLED: { readonly actorMemberId: string | null };
  readonly INSTANCE_EXPIRED: BPMInstanceEventNoPayload;
  readonly INSTANCE_REJECTED: { readonly actorMemberId: string | null };
  readonly INSTANCE_RESUBMITTED: { readonly actorMemberId: string | null };
  readonly INSTANCE_RETURNED: {
    readonly actorMemberId: string | null;
    readonly nodeId: string;
  };
  readonly INSTANCE_SUBMITTED: { readonly actorMemberId: string | null };
  readonly NODE_ACTIVATED: {
    readonly nodeId: string;
    readonly taskIds: readonly string[];
  };
  readonly TASK_AUTO_DECISION_FAILED: {
    readonly reason: string;
    readonly taskId: string;
  };
}

export type BPMInstanceEventType = keyof BPMInstanceEventTypePayloads;

/**
 * Template and state at the moment the event was written. The table has no
 * columns for these, so they are stored inside `payload`.
 */
export interface BPMInstanceEventSnapshot {
  readonly instanceState: ApprovalInstanceStateEnum;
  readonly templateId: string;
  readonly templateKey: string | null;
  readonly templateVersionId: string;
}

/** Columns that every delivered event carries. */
export interface BPMInstanceEventHeader {
  /** Generated by the database. Stable across redeliveries; dedupe on it. */
  readonly id: string;
  readonly instanceId: string;
  /** Write order, assigned by the database. A bigint, so a string. */
  readonly seq: string;
  readonly occurredAt: string;
}

/** The payload stored in `approval_instance_events.payload`. */
export type BPMInstanceEventPayload = {
  readonly [K in BPMInstanceEventType]: BPMInstanceEventSnapshot &
    BPMInstanceEventTypePayloads[K];
}[BPMInstanceEventType];

/** What the observer receives. Discriminated on `type`. */
export type BPMInstanceEvent = {
  readonly [K in BPMInstanceEventType]: BPMInstanceEventHeader & {
    readonly type: K;
  } & BPMInstanceEventSnapshot &
    BPMInstanceEventTypePayloads[K];
}[BPMInstanceEventType];

export const BPM_INSTANCE_EVENT_STATUSES = [
  'PENDING',
  'DELIVERED',
  'FAILED',
] as const;

export type BPMInstanceEventStatus =
  (typeof BPM_INSTANCE_EVENT_STATUSES)[number];
